CREATE DATABASE lesson16_exam;

CREATE TABLE PhongBan(
	IDPB NVARCHAR(20) PRIMARY KEY,
	TenPB NVARCHAR(20) NOT NULL,
    IDNVQL NVARCHAR(20) ,
    NgayBD DATE NOT NULL,
    CONSTRAINT unique_TenPB UNIQUE(TenPB)
);

CREATE TABLE DuAn(
	IDDA NVARCHAR(20) PRIMARY KEY,
    TenDA NVARCHAR(20) NOT NULL,
    Start_Day DATE NOT NULL,
    End_Day DATE NOT NULL,
    TienTD FLOAT NOT NULL,
    IDNVQL NVARCHAR(20),
    CONSTRAINT unique_TenDA UNIQUE(TenDA)
);

CREATE TABLE NhanVien(
	IDNV NVARCHAR(20) PRIMARY KEY,
    NAME_NV NVARCHAR(20) NOT NULL,
    ADRRESS NVARCHAR(20) NOT NULL,
    LUONG FLOAT NOT NULL,
    GioiTinh BIT NOT NULL,
    NgaySinh DATE NOT NULL,
    NgayVaoCT DATE NOT NULL,
    IDDA NVARCHAR(20),
    IDPB NVARCHAR(20),
    CONSTRAINT FK_IDDA FOREIGN KEY (IDDA) REFERENCES DuAn(IDDA) ON DELETE SET NULL,
    CONSTRAINT FK_IDPB FOREIGN KEY (IDPB) REFERENCES PhongBan(IDPB) ON DELETE SET NULL
);

CREATE TABLE QuanLyDuAn(
	ID_QLDA NVARCHAR(20) PRIMARY KEY,
    IDNV NVARCHAR(20),
    IDDA NVARCHAR(20),
    TimeDoJob FLOAT,
    CONSTRAINT FK_IDNV2 FOREIGN KEY (IDNV) REFERENCES NhanVien(IDNV) ON DELETE SET NULL,
    CONSTRAINT FK_IDDA2 FOREIGN KEY (IDDA) REFERENCES DuAn(IDDA) ON DELETE SET NULL
);

