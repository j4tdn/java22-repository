-- Câu 1: Primary key của bảng Result là tổ hợp của cột RESULT_STUDENT_ID và RESULT_SUBJECT 
-- để đảm bảo rằng mỗi học sinh chỉ có một điểm cho mỗi môn học 

-- Câu 2: Liệt kê tên, giới tính và tên giáo viên của tất cả học sinh

SELECT STUDENT.STUDENT_NAME,
       STUDENT.STUDENT_GENDER,
       CLASS.TEACHER_NAME
FROM STUDENT
JOIN CLASS ON STUDENT.STUDENT_CLASS_ID = CLASS.CLASS_ID
GROUP BY STUDENT.STUDENT_NAME, STUDENT.STUDENT_GENDER, CLASS.TEACHER_NAME;

-- Câu 3: Liệt kê tên giáo viên và số lượng học sinh lớp 12C

SELECT CLASS.TEACHER_NAME,
       COUNT(STUDENT.STUDENT_ID) AS number_of_students
FROM STUDENT
JOIN CLASS ON STUDENT.STUDENT_CLASS_ID = CLASS.CLASS_ID
WHERE CLASS.CLASS_NAME = '12C'
GROUP BY CLASS.TEACHER_NAME;

-- Câu 4: Liệt kê tên lớp và số lượng học sinh có điểm Toán>=8 và Văn>=8

SELECT CLASS.CLASS_NAME,
       COUNT(DISTINCT STUDENT.STUDENT_ID) AS number_of_students
FROM STUDENT
JOIN CLASS ON STUDENT.STUDENT_CLASS_ID = CLASS.CLASS_ID 
JOIN RESULT r1 ON STUDENT.STUDENT_ID = r1.RESULT_STUDENT_ID 
AND r1.RESULT_SUBJECT = 'Math' AND r1.RESULT_SCORE >= 8
JOIN RESULT r2 ON STUDENT.STUDENT_ID = r2.RESULT_STUDENT_ID 
AND r2.RESULT_SUBJECT = 'Literature' AND r2.RESULT_SCORE >= 8
GROUP BY CLASS.CLASS_NAME

 



