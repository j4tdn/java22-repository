DROP DATABASE IF EXISTS lesson17_exam;
CREATE DATABASE lesson17_exam CHAR SET utf8mb4;
USE lesson17_exam;

CREATE TABLE CLASS (
   CLASS_ID INT PRIMARY KEY AUTO_INCREMENT,
   CLASS_NAME VARCHAR(255) NOT NULL,
   TEACHER_NAME  VARCHAR(255) NOT NULL
);

CREATE TABLE STUDENT (
   STUDENT_ID INT PRIMARY KEY AUTO_INCREMENT,
   STUDENT_NAME VARCHAR(255) NOT NULL,
   STUDENT_GENDER VARCHAR(10) NOT NULL,
   STUDENT_CLASS_ID INT NOT NULL,
   CONSTRAINT FK_STUDENT_CLASS FOREIGN KEY (STUDENT_CLASS_ID) 
                               REFERENCES CLASS(CLASS_ID)
);

CREATE TABLE RESULT (
   RESULT_STUDENT_ID INT NOT NULL,
   RESULT_SUBJECT VARCHAR(255) NOT NULL,
   RESULT_SCORE DECIMAL(4,1),
   PRIMARY KEY (RESULT_STUDENT_ID, RESULT_SUBJECT),
   CONSTRAINT FK_RESULT_STUDENT FOREIGN KEY (RESULT_STUDENT_ID) 
                               REFERENCES STUDENT(STUDENT_ID)
);

