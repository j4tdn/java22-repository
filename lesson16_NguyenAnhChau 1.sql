-- Phần A. Phân tích và viết các lệnh để xây dựng cơ sở dữ liệu dựa vào mô tả phía trên
CREATE TABLE t03_roles_company(
C03_ROLES_COMPANY_ID INT primary key auto_increment,
C03_ROLES_COMPANY_NAME VARCHAR(255) NOT NULL,
constraint C03_CHECK CHECK (C03_ROLES_COMPANY_NAME IN ('Head','Employee'))
);

CREATE TABLE t02_department(
C02_DEPARTMENT_ID INT primary key auto_increment,
C02_DEPARTMENT_NAME varchar(255) NOT NULL,
C02_DEPARTMENT_HEAD_ID INT ,
C02_DEPARTMENT_TAKEOVER_DAY DATE ,
CONSTRAINT UNI_C02_DEPARTMENT_NAME UNIQUE(C02_DEPARTMENT_NAME),
CONSTRAINT UNI_C02_DEPARTMENT_HEAD_ID UNIQUE(C02_DEPARTMENT_NAME)
);
ALTER TABLE t02_department ADD CONSTRAINT FK_T02_T01 FOREIGN KEY (C02_DEPARTMENT_HEAD_ID)
													REFERENCES t01_employee(C01_EMPLOYEE_ID);

CREATE TABLE t04_project(
C04_PROJECT_ID INT PRIMARY KEY AUTO_INCREMENT,
C04_PROJECT_NAME VARCHAR(255) NOT NULL,
C04_PROJECT_HEAD_EMPLOYEE_ID INT ,
C04_PROJECT_START_DAY DATE NOT NULL,
C04_PROJECT_END_DAY DATE NOT NULL,
C04_PROJECT_PROFIT INT NOT NULL
);
ALTER TABLE t04_project ADD CONSTRAINT FK_T04_T01 FOREIGN KEY (C04_PROJECT_HEAD_EMPLOYEE_ID)
													REFERENCES t01_employee(C01_EMPLOYEE_ID);


CREATE TABLE t01_employee(
C01_EMPLOYEE_ID INT PRIMARY KEY AUTO_INCREMENT,
C01_DEPARTMENT_ID INT NOT NULL,
C01_EMPLOYEE_MONITOR_ID INT ,
C01_ROLES_COMPANY_ID INT NOT NULL,
C01_EMPLOYEE_NAME VARCHAR(255) NOT NULL,
C01_EMPLOYEE_ADDRESS VARCHAR(255) NOT NULL,
C01_EMPLOYEE_SALARY VARCHAR(255) NOT NULL,
C01_EMPLOYEE_GENDER VARCHAR(255) NOT NULL,
C01_EMPLOYEE_BIRTHDAY VARCHAR(255) NOT NULL,
C01_EMPLOYEE_START_WORKING_DAY VARCHAR(255) NOT NULL,
CONSTRAINT FK_T01_T02 FOREIGN KEY (C01_DEPARTMENT_ID)
						REFERENCES T02_DEPARTMET(C02_DEPARTMENT_ID),
CONSTRAINT FK_T01_T03 FOREIGN KEY (C01_ROLES_COMPANY_ID)
						REFERENCES T03_ROLES_COMPANY(C03_ROLES_COMPANY_ID)
                        
);
ALTER TABLE t01_employee DROP COLUMN C01_EMPLOYEE_GENDER;
ALTER TABLE t01_employee ADD COLUMN C01_EMPLOYEE_GENDER BIT(1) NOT NULL;

CREATE TABLE t05_employee_project(
C05_EMPLOYEE_PROJECT_ID INT PRIMARY KEY AUTO_INCREMENT,
C05_EMPLOYEE_ID INT NOT NULL,
C05_PROJECT_ID INT NOT NULL,
C05_EMPLOYEE_PROJECT_TIME_WORKING INT NOT NULL,
CONSTRAINT FK_T05_T01 FOREIGN KEY (C05_EMPLOYEE_ID)
						REFERENCES T01_EMPLOYEE(C01_EMPLOYEE_ID),
CONSTRAINT FK_T05_T04 FOREIGN KEY (C05_PROJECT_ID)
						REFERENCES T04_PROJECT(C04_PROJECT_ID),
CONSTRAINT T05_UNI UNIQUE(C05_EMPLOYEE_ID,C05_PROJECT_ID)

);



