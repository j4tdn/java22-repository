
CREATE DATABASE company_management CHAR SET utf8mb4;
use company_management;
CREATE TABLE T01_DEPARTMENT(
	C01_ID_DEPT INT PRIMARY KEY AUTO_INCREMENT,
	C01_DEPT_NAME VARCHAR(255) NOT NULL, 
	C01_ID_HEAD_DEPT INT NOT NULL,
	C01_DAY_TAKE DATE NOT NULL,
    CONSTRAINT UNQ_T01_T01_DEPT_NAME UNIQUE(C01_DEPT_NAME)

);

CREATE TABLE T02_EMPLOYEE(
	C02_ID_EMP INT PRIMARY KEY AUTO_INCREMENT,
	C02_NAME_EMP VARCHAR(255) NOT NULL,
	C02_ADDRESS TEXT NOT NULL,
	C02_SALARY DECIMAL(10,2),
	C02_GENDER BIT NOT NULL,
	C02_DATE_OF_BIRTH DATE NOT NULL,
	C02_JOIN_DATE DATE NOT NULL,
	C02_EMP_MANAGER_ID INT NOT NULL,
	C02_ID_DEPT INT NOT NULL,
    
    CONSTRAINT FK_T02 FOREIGN KEY (C02_EMP_MANAGER_ID) REFERENCES T02_EMPLOYEE(C02_ID_EMP)

);

ALTER TABLE T01_DEPARTMENT
ADD CONSTRAINT FK_T01_T02 FOREIGN KEY (C01_ID_HEAD_DEPT) REFERENCES T02_EMPLOYEE(C02_ID_EMP);

ALTER TABLE T02_EMPLOYEE
ADD CONSTRAINT FK_T02_T01 FOREIGN KEY (C02_ID_DEPT) REFERENCES T01_DEPARTMENT(C01_ID_DEPT);

CREATE TABLE T03_PROJECT(
	C03_ID_PROJECT INT PRIMARY KEY AUTO_INCREMENT ,
	C03_NAME_PROJECT VARCHAR(255) NOT NULL,
	C03_BEGIN_DATE DATE NOT NULL,
	C03_END_DATE DATE NOT NULL,
	C03_PROCEEDS DECIMAL(10,2),
	C03_ID_PROJECT_MANAGER INT NOT NULL,
    CONSTRAINT UNQ_T03_NAME_PROJECT UNIQUE(C03_NAME_PROJECT),
    CONSTRAINT FK_T03_T02 FOREIGN KEY (C03_ID_PROJECT_MANAGER) REFERENCES T02_EMPLOYEE(C02_ID_EMP)
);

CREATE TABLE T04_PROJECT_DETAIL(
	C04_ID_PROJECT_DETAIL INT PRIMARY KEY AUTO_INCREMENT,
	C04_ID_PROJECT INT NOT NULL,
	C04_ID_EMP INT NOT NULL,
	C04_WORKING_HOURS INT NOT NULL

);
ALTER TABLE T04_PROJECT_DETAIL
ADD CONSTRAINT FK_T04_T03_ID_PROJECT FOREIGN KEY (C04_ID_PROJECT) REFERENCES T03_PROJECT(C03_ID_PROJECT);

ALTER TABLE T04_PROJECT_DETAIL
ADD CONSTRAINT FK_T04_T02_ID_EMP FOREIGN KEY (C04_ID_EMP) REFERENCES T02_EMPLOYEE(C02_ID_EMP);

